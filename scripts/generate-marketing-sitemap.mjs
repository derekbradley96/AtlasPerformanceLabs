/**
 * Regenerates public/sitemap.xml from marketing routes (keep in sync with MarketingLayout NAV + join).
 * Run automatically before vite build.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'public', 'sitemap.xml');

const BASE = 'https://atlasperformancelabs.co.uk';
const lastmod = new Date().toISOString().slice(0, 10);

/** Mirrors src/pages/marketing/MarketingLayout.jsx NAV + /join + blog from AppRoutes. */
const ENTRIES = [
  { path: '/', changefreq: 'weekly', priority: '1.0' },
  { path: '/for-coaches', changefreq: 'monthly', priority: '0.9' },
  { path: '/for-clients', changefreq: 'monthly', priority: '0.8' },
  { path: '/personal', changefreq: 'monthly', priority: '0.8' },
  { path: '/pricing', changefreq: 'monthly', priority: '0.9' },
  { path: '/marketplace', changefreq: 'weekly', priority: '0.8' },
  { path: '/affiliates', changefreq: 'monthly', priority: '0.6' },
  { path: '/why-switch', changefreq: 'monthly', priority: '0.8' },
  { path: '/join', changefreq: 'monthly', priority: '0.7' },
];

/** Blog URLs use fixed lastmod for evergreen posts (align with Search Console expectations). */
const BLOG_ENTRIES = [
  { path: '/blog', changefreq: 'weekly', priority: '0.7', lastmod: '2026-04-21' },
  { path: '/blog/how-to-run-peak-week-first-time', changefreq: 'monthly', priority: '0.7', lastmod: '2026-04-21' },
  { path: '/blog/best-competition-prep-coaching-software', changefreq: 'monthly', priority: '0.7', lastmod: '2026-04-21' },
  { path: '/blog/macro-tracking-bodybuilding-complete-guide', changefreq: 'monthly', priority: '0.7', lastmod: '2026-04-21' },
];

function urlBlock({ path: p, changefreq, priority, lastmod: entryLastmod }) {
  const loc = `${BASE}${p === '/' ? '/' : p}`;
  const mod = entryLastmod || lastmod;
  return `  <url>
    <loc>${loc}</loc>
    <lastmod>${mod}</lastmod>
    <changefreq>${changefreq}</changefreq>
    <priority>${priority}</priority>
  </url>`;
}

const body = [...ENTRIES.map(urlBlock), ...BLOG_ENTRIES.map(urlBlock)].join('\n');
const xml = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">

  <!-- Core marketing pages (generated by scripts/generate-marketing-sitemap.mjs) -->
${body}

</urlset>
`;

fs.writeFileSync(OUT, xml, 'utf8');
const n = ENTRIES.length + BLOG_ENTRIES.length;
console.log('Wrote', path.relative(ROOT, OUT), `(${n} URLs, core lastmod ${lastmod})`);
